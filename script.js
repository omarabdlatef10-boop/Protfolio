// ========== Typing effect ==========
const typingEl = document.getElementById("typing");
let typingWords = I18N[currentLang].typingWords;
let wordIndex = 0;
let charIndex = 0;
let deleting = false;
let typingGeneration = 0;

function type(gen = typingGeneration) {
  if (gen !== typingGeneration) return;
  const word = typingWords[wordIndex];
  if (!deleting) {
    typingEl.textContent = word.slice(0, ++charIndex);
    if (charIndex === word.length) {
      deleting = true;
      setTimeout(() => type(gen), 1600);
      return;
    }
  } else {
    typingEl.textContent = word.slice(0, --charIndex);
    if (charIndex === 0) {
      deleting = false;
      wordIndex = (wordIndex + 1) % typingWords.length;
    }
  }
  setTimeout(() => type(gen), deleting ? 80 : 130);
}
type();

