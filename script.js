// ========== About gallery ==========
const galleryTrack = document.getElementById("galleryTrack");
const gallerySlides = Array.from(document.querySelectorAll(".gallery-slide"));
const galleryDots = Array.from(document.querySelectorAll("#galleryDots .dot"));
const galleryPrevBtn = document.getElementById("galleryPrev");
const galleryNextBtn = document.getElementById("galleryNext");
const galleryCounter = document.getElementById("galleryCounter");
let galleryIndex = 0;
let dragStartX = null;
let dragDelta = 0;
let isDragging = false;

function showGallerySlide(index) {
  if (!gallerySlides.length) return;
  galleryIndex = (index + gallerySlides.length) % gallerySlides.length;
  gallerySlides.forEach((slide, i) => slide.classList.toggle("active", i === galleryIndex));
  galleryDots.forEach((dot, i) => {
    const active = i === galleryIndex;
    dot.classList.toggle("active", active);
    if (active) dot.setAttribute("aria-current", "true");
    else dot.removeAttribute("aria-current");
  });
  galleryCounter.textContent = `${galleryIndex + 1} / ${gallerySlides.length}`;
}

galleryPrevBtn.addEventListener("click", () => showGallerySlide(galleryIndex - 1));
galleryNextBtn.addEventListener("click", () => showGallerySlide(galleryIndex + 1));
galleryDots.forEach((dot) =>
  dot.addEventListener("click", () => showGallerySlide(Number(dot.dataset.index)))
);

galleryTrack.addEventListener("keydown", (e) => {
  if (e.key === "ArrowLeft") {
    showGallerySlide(galleryIndex + 1);
    e.preventDefault();
  } else if (e.key === "ArrowRight") {
    showGallerySlide(galleryIndex - 1);
    e.preventDefault();
  }
});

function resetDragSlide() {
  const slide = gallerySlides[galleryIndex];
  if (!slide) return;
  slide.style.transition = "";
  slide.style.transform = "";
}

galleryTrack.addEventListener("pointerdown", (e) => {
  if (e.pointerType === "mouse" && e.button !== 0) return;
  isDragging = true;
  dragStartX = e.clientX;
  dragDelta = 0;
  galleryTrack.classList.add("dragging");
  const slide = gallerySlides[galleryIndex];
  if (slide) {
    slide.style.transition = "none";
    slide.style.transform = "translateX(0) scale(1)";
  }
  if (galleryTrack.setPointerCapture) galleryTrack.setPointerCapture(e.pointerId);
});

galleryTrack.addEventListener("pointermove", (e) => {
  if (!isDragging || dragStartX === null) return;
  dragDelta = Math.max(-140, Math.min(140, e.clientX - dragStartX));
  const slide = gallerySlides[galleryIndex];
  if (slide) slide.style.transform = `translateX(${dragDelta}px) scale(1)`;
});

function endDrag(e) {
  if (!isDragging) return;
  isDragging = false;
  galleryTrack.classList.remove("dragging");
  resetDragSlide();
  if (dragStartX !== null && Math.abs(dragDelta) > 50) {
    showGallerySlide(galleryIndex + (dragDelta < 0 ? 1 : -1));
  }
  dragStartX = null;
  dragDelta = 0;
  if (
    e &&
    galleryTrack.hasPointerCapture &&
    galleryTrack.hasPointerCapture(e.pointerId)
  ) {
    galleryTrack.releasePointerCapture(e.pointerId);
  }
}

galleryTrack.addEventListener("pointerup", endDrag);
galleryTrack.addEventListener("pointercancel", endDrag);
galleryTrack.addEventListener("lostpointercapture", endDrag);
showGallerySlide(0);

