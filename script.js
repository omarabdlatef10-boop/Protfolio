let currentLang = localStorage.getItem("omar-lang") === "en" ? "en" : "ar";

function applyLang(lang) {
  currentLang = lang;
  const t = I18N[lang];
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t[el.dataset.i18n];
    if (value !== undefined) el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = t[el.dataset.i18nHtml];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const value = t[el.dataset.i18nPlaceholder];
    if (value !== undefined) el.placeholder = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = t[el.dataset.i18nAria];
    if (value !== undefined) el.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = t[el.dataset.i18nAlt];
    if (value !== undefined) el.alt = value;
  });

  document.title = t.docTitle;
  document.querySelector('meta[name="description"]').content = t.docDesc;

  const langBtn = document.getElementById("langToggle");
  langBtn.textContent = t.langShort;
  langBtn.title = lang === "ar" ? "Switch to English" : "التبديل للعربية";
  document.getElementById("themeToggle").title = t.themeTitle;
  document.getElementById("menuToggle").setAttribute("aria-label", t.menuLabel);

  typingWords = t.typingWords;
  typingGeneration++;
  wordIndex = 0;
  charIndex = 0;
  deleting = false;
  typingEl.textContent = "";
  type(typingGeneration);

  localStorage.setItem("omar-lang", lang);
}

